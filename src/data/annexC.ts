// Build a lookup keyed by the sorted set of the 8 qualifying groups.
const LOOKUP: Record<string, string> = {};
for (const row of OPTIONS) {
  const key = row.split('').sort().join('');
  LOOKUP[key] = row;
}

/**
 * Given the 8 groups whose third-placed teams qualified, return the
 * mapping winner-slot group -> third-placed group it faces in the R32.
 * Returns null if no matching Annex C combination exists.
 */
export function thirdPlaceAssignment(
  qualifiedGroups: GroupLetter[],
): Record<GroupLetter, GroupLetter> | null {
  if (qualifiedGroups.length !== 8) return null;
  const key = [...qualifiedGroups].sort().join('');
  const row = LOOKUP[key];
  if (!row) return null;
  const out = {} as Record<GroupLetter, GroupLetter>;
  ANNEX_C_WINNER_ORDER.forEach((winnerSlot, i) => {
    out[winnerSlot] = row[i] as GroupLetter;
  });
  return out;
}
